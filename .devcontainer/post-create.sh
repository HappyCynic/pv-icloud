# Runs once inside the container after it is created.
set -euo pipefail

# Named volumes can predate the image's chown (e.g. after a rebuild).
sudo chown -R vscode:vscode /home/vscode/.venv /home/vscode/.cache/uv /home/vscode/.claude /data

# SSH. By default the editor forwards its own agent ($SSH_AUTH_SOCK) and nothing else is
# needed. If compose.local.yaml mounts a host agent at /run/ssh-agent.sock and/or the host's
# ~/.ssh at ~/.ssh-host (see compose.local.example.yaml), use them for ssh and git signing.
mkdir -p ~/.ssh && chmod 700 ~/.ssh
{
  echo "# Generated by .devcontainer/post-create.sh; edit there."
  # ssh_config takes the first value it sees, so these lines override the host config's
  # own (e.g. macOS-only) IdentityAgent path.
  if [[ -S /run/ssh-agent.sock ]]; then
    printf 'Host *\n    IdentityAgent /run/ssh-agent.sock\n'
  fi
  if [[ -f ~/.ssh-host/config ]]; then
    printf 'Host *\n    UserKnownHostsFile ~/.ssh/known_hosts ~/.ssh-host/known_hosts\n\n'
    printf 'Include ~/.ssh-host/config\n'
  fi
} > ~/.ssh/config
chmod 600 ~/.ssh/config

# Git signs commits with ssh-keygen, which reads $SSH_AUTH_SOCK, not ~/.ssh/config: point
# it at the host agent through a wrapper. System config, so the editor's copy of the host's
# ~/.gitconfig stays untouched.
if [[ -S /run/ssh-agent.sock ]]; then
  printf '%s\n' '#!/bin/sh' \
    '# Generated by .devcontainer/post-create.sh: git commit signing via the host SSH agent.' \
    'SSH_AUTH_SOCK=/run/ssh-agent.sock exec ssh-keygen "$@"' \
    | sudo tee /usr/local/bin/ssh-keygen-host-agent >/dev/null
  sudo chmod 755 /usr/local/bin/ssh-keygen-host-agent
  sudo git config --system gpg.ssh.program /usr/local/bin/ssh-keygen-host-agent
fi

python --version
uv --version

# The mail index depends on SQLite FTS5; fail loudly if this Python lacks it.
python - <<'EOF'
import sqlite3
con = sqlite3.connect(":memory:")
con.execute("CREATE VIRTUAL TABLE t USING fts5(x)")
print(f"sqlite {sqlite3.sqlite_version}: FTS5 OK")
EOF

if [[ -f pyproject.toml ]]; then
  uv sync --all-groups
else
  echo "No pyproject.toml yet; skipping uv sync."
fi
